#!/usr/bin/env bash
# Reconstruct and restore the DB5 portable data stored as git split parts.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="${TRADOCK_DIR:-$(cd "$SCRIPT_DIR/.." && pwd)}"
DATA_DIR="${DATA_DIR:-$PROJECT_ROOT/portable_data}"
WORK_DIR="${WORK_DIR:-$HOME/tradock_restore_work}"
INSTALL_ROOT="${INSTALL_ROOT:-$HOME/tradock_data}"
ARCHIVE_NAME="${ARCHIVE_NAME:-tradock_db5_eval_pack_20260714_154813_portable.tar.gz}"
LOCAL_ENV_FILE="${LOCAL_ENV_FILE:-$PROJECT_ROOT/environment.local}"

mkdir -p "$WORK_DIR"

if ! compgen -G "$DATA_DIR/$ARCHIVE_NAME.part-*" >/dev/null; then
    echo "[error] missing split data parts: $DATA_DIR/$ARCHIVE_NAME.part-*"
    exit 1
fi

echo "=== Rebuild portable archive ==="
cat "$DATA_DIR/$ARCHIVE_NAME".part-* > "$WORK_DIR/$ARCHIVE_NAME"
cp "$DATA_DIR/$ARCHIVE_NAME.sha256" "$WORK_DIR/$ARCHIVE_NAME.sha256"

echo "=== Verify checksum ==="
(cd "$WORK_DIR" && shasum -a 256 -c "$ARCHIVE_NAME.sha256")

echo "=== Extract outer archive ==="
rm -rf "$WORK_DIR/extracted"
mkdir -p "$WORK_DIR/extracted"
tar -xzf "$WORK_DIR/$ARCHIVE_NAME" -C "$WORK_DIR/extracted"

INNER_ARCHIVE="$(find "$WORK_DIR/extracted" -path '*/portable_data/tradock_db5_portable_data_latest.tar.gz' -print -quit)"
if [ -z "$INNER_ARCHIVE" ]; then
    echo "[error] missing inner portable data archive"
    exit 1
fi

echo "=== Restore data to $INSTALL_ROOT ==="
mkdir -p "$INSTALL_ROOT"
TAR_ARGS=(-xzf "$INNER_ARCHIVE" -C "$INSTALL_ROOT")
if [ "$INSTALL_ROOT" != "/" ]; then
    TAR_ARGS+=(--strip-components=1)
    RESTORE_BASE="$INSTALL_ROOT"
else
    RESTORE_BASE="/root"
fi
tar "${TAR_ARGS[@]}"

PPC_PATH="$RESTORE_BASE/PPCBench"
HDOCK_PATH="$RESTORE_BASE/autodl-tmp/tools/hdocklite_full/hdock"
CREATEPL_PATH="$RESTORE_BASE/autodl-tmp/tools/hdocklite_full/createpl"
CHECKPOINT_PATH="$RESTORE_BASE/TraDock/Trained_models/pretrain_with_sasa/TransformerDock_best.chk"

cat > "$LOCAL_ENV_FILE" <<EOF
# Local paths generated by scripts/restore_repo_data.sh
export PPC_ROOT="$PPC_PATH"
export PAPER_ROOT="$PPC_PATH"
export HDOCK_BIN="$HDOCK_PATH"
export CREATEPL_BIN="$CREATEPL_PATH"
export CHECKPOINT="$CHECKPOINT_PATH"
export DB5_EVAL_RUN_ROOT="$RESTORE_BASE/db5_three_method_eval"
export COLABFOLD_DATA="\${COLABFOLD_DATA:-$RESTORE_BASE/colabfold_params_v3}"
EOF

echo "=== Done ==="
echo "Restored expected paths:"
echo "  $PPC_PATH"
echo "  $(dirname "$HDOCK_PATH")"
echo "  $CHECKPOINT_PATH"
echo ""
echo "Wrote local environment:"
echo "  $LOCAL_ENV_FILE"
echo ""
echo "Next for other methods:"
echo "  bash scripts/install_lightdock.sh"
echo "  bash scripts/setup_colabfold_paths.sh"
echo ""
echo "Verify:"
echo "  cd $PROJECT_ROOT && METHODS=hdock bash scripts/verify_full_eval.sh"
